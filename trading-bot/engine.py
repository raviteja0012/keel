# Smallest position that can actually be halved at TP1. The live path already
# gates its partial close on this (0.01 lots cannot be split), so paper must model
# the same limit or the sample that opens the promotion gate is generated by a fill
# the first live weeks - run at minimum size by design - structurally cannot produce.
