# ------------------------------------------------------------ sizing
def calc_lots(symbol: str, entry: float, sl: float, risk_amount: float):
    """Broker-exact sizing from tick_value/tick_size pushed by the EA.
    Returns (lots, actual_risk) so the caller can record the TRUE risk
    after lot rounding (min-lot floors can otherwise overstate it)."""
    p = feed_state["prices"].get(symbol)
    if not p:
        return 0.0, 0.0
    tick_value = p.get("tick_value") or 0
    tick_size = p.get("tick_size") or 0
    if tick_value <= 0 or tick_size <= 0:
        return 0.0, 0.0
    loss_per_lot = abs(entry - sl) / tick_size * tick_value
    if loss_per_lot <= 0:
        return 0.0, 0.0
    lots = max(0.01, int(risk_amount / loss_per_lot * 100) / 100.0)
    return lots, round(lots * loss_per_lot, 2)


# ------------------------------------------------- unrealized P&L
def trade_upnl(tr: Dict) -> Optional[float]:
    """Unrealized P&L of an open trade. Live trades use the broker's own
    number (includes swap/commission); paper trades are marked to the
    exit side of the book (bid for longs, ask for shorts)."""
    if tr["mode"] == "live":
        pos = next((x for x in feed_state["open_positions"]
                    if x.get("ticket") == tr["ticket"]
                    or "SLC#%d" % tr["id"] in (x.get("comment") or "")), None)
        if pos is not None:
            return round((pos.get("unrealized_pnl") or 0) + (pos.get("swap") or 0), 2)
    p = feed_state["prices"].get(tr["symbol"])
    if not p:
        return None
    tick_value = p.get("tick_value") or 0
    tick_size = p.get("tick_size") or 0
    if tick_value <= 0 or tick_size <= 0:
        return None
    cur = p["bid"] if tr["side"] == "buy" else p["ask"]
    direction = 1 if tr["side"] == "buy" else -1
    pnl = (cur - tr["entry"]) * direction / tick_size * tick_value * tr["lots"]
    if tp1_partial_taken(tr):
        # half was banked at +1R: value it from price distance (exact),
        # not from the recorded risk_amount
        banked = abs(tr["entry"] - tr["initial_sl"]) / tick_size * tick_value * tr["lots"]
        pnl = pnl * 0.5 + banked * 0.5
    return round(pnl, 2)


def open_pnl_total() -> float:
    return round(sum(trade_upnl(t) or 0 for t in storage.open_trades()), 2)


# ----------------------------------------------------- loss limits
def round_turn_cost(tr: Dict[str, Any], price: float) -> float:
    """What the round turn costs, in account currency. Never negative.

    Paper P&L was pure price movement while live P&L reads profit + commission +
    swap off the broker deal. So the 50-trade sample that opens the promotion gate
    was measured GROSS and the live results it is meant to predict are NET. At a
    profit factor near 1.1 that difference is the whole edge, and the gate would
    happily certify a strategy whose net expectancy is negative.

    Three components, because the venues charge differently:
      per-lot commission   how MT5 brokers usually bill FX and metals
      taker fee on notional  how every crypto exchange bills, 0.10% to 1.20%
      slippage             a fixed haircut per side; entering and exiting at the
                           mid price is a fiction no live account gets

    Defaults are deliberately non-zero. A cost model that defaults to free is the
    same bug in a nicer suit."""
    s = storage.all_settings()
    p = feed_state["prices"].get(tr["symbol"], {})
    tick_size = p.get("tick_size") or 0
    tick_value = p.get("tick_value") or 0
    lots = float(tr.get("lots") or 0)

    commission = float(s.get("paper_commission_per_lot", 7.0)) * lots

    taker = float(s.get("paper_taker_fee_pct", 0.0))
    notional = 0.0
    if taker and tick_size > 0 and tick_value > 0:
        # value of a 1.0 price move, scaled to the traded price on both sides
        per_price_unit = tick_value / tick_size * lots
        notional = (abs(tr.get("entry") or 0) + abs(price or 0)) * per_price_unit
    fee = notional * taker / 100.0

    slip_pts = float(s.get("paper_slippage_points", 1.0))
    slippage = 0.0
    if slip_pts and tick_size > 0 and tick_value > 0:
        slippage = 2 * slip_pts * tick_value * lots      # entry side and exit side

    return round(max(0.0, commission + fee + slippage), 4)


def tp1_partial_taken(tr: Dict[str, Any]) -> bool:
    """Was half the position ACTUALLY banked at TP1, or only the stop moved?

    tp1_done means "price reached +1R, stop is now at breakeven" and applies in
    both modes. Banking 50% is a separate question, because a 0.01-lot position
    cannot be halved. Paper used to assume the partial always happened; live
    refuses it below MIN_PARTIAL_LOTS. Same predicate for both now, so paper P&L
    matches what a minimum-size live account would really have realised."""
    return bool(tr["tp1_done"]) and (tr["lots"] or 0) >= MIN_PARTIAL_LOTS


def _pnl_since(mode: str, since_ts: int) -> float:
    row = storage.query_one(
        "SELECT COALESCE(SUM(pnl),0) s FROM trades "
        "WHERE mode=? AND status='closed' AND exit_time>=?", (mode, since_ts))
    return row["s"] if row else 0.0


def _open_pnl(mode: str) -> Tuple[float, int]:
    """Open P&L, and how many positions could NOT be valued.

    The count is the point. This used to be sum(trade_upnl(t) or 0), which turns
    an UNKNOWN into a ZERO, and zero reads as "that position is flat" - the most
    reassuring possible answer to a question we could not answer. A venue whose
    symbol_meta call failed writes a price record with no tick_value, trade_upnl
    then returns None for every position quoted from it, and the open drawdown
    feeding the daily and weekly kill switches becomes exactly nothing while the
    book is underwater. Invariant 9 defeated, silently, by an `or 0`.

    Callers get the count and must decide. Nobody may collapse it back to one
    number."""
    total, unknown = 0.0, 0
    for t in storage.open_trades(mode):
        v = trade_upnl(t)
        if v is None:
            unknown += 1
        else:
            total += v
    return round(total, 2), unknown


def _broker_offset() -> float:
    term = feed_state.get("terminal", {})
    return (term.get("time_local") or 0) - (term.get("time_utc") or 0)


def loss_limits_hit(mode: str, balance: float, p: Dict) -> Optional[str]:
    """Daily/weekly kill switches. The loss 'day' follows the broker clock
    (statements cut there, not at UTC midnight), and OPEN drawdown counts
    against the stop — being -2% underwater on open positions halts new
    entries just as surely as -2% realized. Open profit never offsets
    realized losses (conservative by construction)."""
    if balance <= 0:
        return None
    day0, week0 = sessions.day_week_start("broker", broker_offset_s=_broker_offset())
    open_pnl, unvalued = _open_pnl(mode)

    # A position we cannot value is not a position worth nothing. If any open
    # trade has no usable quote, the drawdown feeding these stops is understated
    # by an unknown amount, so the honest reading of "am I past my daily stop?"
    # is "I cannot tell" - and the fail-closed answer to that is to stop opening
    # new ones. This does NOT touch existing positions; their stops are managed
    # on the last confirmed price by manage_open_trades.
    if unvalued:
        return ("cannot value %d open position%s (no usable quote) — open "
                "drawdown is unknown, so new entries stand aside"
                % (unvalued, "" if unvalued == 1 else "s"))

    open_dd = min(0.0, open_pnl)
    if _pnl_since(mode, day0) + open_dd <= -balance * p["daily_stop_pct"] / 100:
        return "daily stop (-%.1f%%) hit" % p["daily_stop_pct"]
    if _pnl_since(mode, week0) + open_dd <= -balance * p["weekly_stop_pct"] / 100:
        return "weekly stop (-%.1f%%) hit" % p["weekly_stop_pct"]
    return None


def loss_governor(mode: str) -> float:
    """Playbook §10.3: after 3 consecutive losses, halve risk until 2
    consecutive wins. Derived from the trades table (restart-safe — no
    counters to lose)."""
    # pnl IS NOT NULL matters: "(r['pnl'] or 0) < 0" reads NULL as a WIN, so a
    # closed row that never got its pnl written would reset the loss streak and
    # silently un-halve risk. Invariant 10 must not be defeated by bad data.
    rows = storage.query(
        "SELECT pnl FROM trades WHERE mode=? AND status='closed' "
        "AND pnl IS NOT NULL ORDER BY exit_time DESC LIMIT 50", (mode,))
    halved, consec_loss, consec_win = False, 0, 0
    for r in reversed(rows):                       # oldest -> newest
        if (r["pnl"] or 0) < 0:
            consec_loss += 1
            consec_win = 0
            if consec_loss >= 3:
                halved = True
        else:
            consec_win += 1
            consec_loss = 0
            if halved and consec_win >= 2:
                halved = False
    return 0.5 if halved else 1.0


def _balance(mode: str, p: Dict) -> float:
    if mode == "live":
        return float(feed_state["account"].get("balance", 0) or 0)
    closed = storage.query_one(
        "SELECT COALESCE(SUM(pnl),0) s FROM trades WHERE mode='paper' AND status='closed'")
    return p["paper_balance"] + (closed["s"] if closed else 0)


